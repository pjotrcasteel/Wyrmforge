export function mageFrameKey(cast, walkPhase = 0) {
    if (!cast || !Number.isFinite(cast.progress) || cast.progress < 0 || cast.progress >= 1)
        return walkPhase === 1 ? 'walkA' : walkPhase === 2 ? 'walkB' : 'idle';
    if (cast.progress < .22) return 'windup';
    if (cast.progress < .48) return cast.surge ? 'surgeRelease' : 'release';
    return 'followThrough';
}

