using Wyrmforge.Domain.Combat.Geometry;
using Wyrmforge.Domain.Progression.Signature;
using Wyrmforge.Application.Runs.Navigation;

namespace Wyrmforge.Application.Runs.Navigation;

/// <summary>One bounded, C#-authored physical footprint. Render and collision consume exactly this polygon.</summary>
public sealed record WorldSiteObstacle(
    string Kind,
    WorldSiteSurfaceId Material,
    double Height,
    IReadOnlyList<HuntPoint> Outline);

/// <summary>Visible C# elevation and grade, traversable unless a separate physical footprint blocks it.</summary>
public sealed record WorldSiteTerrainPatch(
    string Kind,
    WorldSiteSurfaceId Material,
    double Height,
    double Slope,
    IReadOnlyList<HuntPoint> Outline);

/// <summary>A seed-stable optional point of interest. Reward identity belongs to this physical site, not to renderer art.</summary>
public sealed record WorldSiteDiscovery(string Id, string Kind, HuntPoint LocalPoint, HuntMaterialId? MaterialReward);

/// <summary>A landmark-shaped site plan, not a new simulation or rendering engine.</summary>
public sealed record WorldSiteLandscapeRecipe(
    string Kind,
    IReadOnlyList<WorldSiteObstacle> Obstacles)
{
    /// <summary>Gradual highland surfaces and terraces generated by C#, separate from collision.</summary>
    public IReadOnlyList<WorldSiteTerrainPatch> TerrainPatches { get; init; } = [];

    /// <summary>Local access paths chosen by the site generator, unrelated to Chart graph edges.</summary>
    public IReadOnlyList<WorldSiteCorridor> LocalPaths { get; init; } = [];

    /// <summary>Optional grounded sites, possibly empty; the Hunt decides whether an unclaimed reward can be collected.</summary>
    public IReadOnlyList<WorldSiteDiscovery> Discoveries { get; init; } = [];
}

/// <summary>Deterministic local scenery from world-map habitat and landmark metadata, without consuming combat or reward RNG.</summary>
public static class WorldSiteLandscapeGenerator
{
    /// <summary>Creates seeded place geometry while reserving mapped exit clearance and local scenic trails.</summary>
    public static WorldSiteLandscapeRecipe Generate(WyrmrealmMapNode node, WorldSiteGeography geography)
    {
        ArgumentNullException.ThrowIfNull(node);
        ArgumentNullException.ThrowIfNull(geography);
        var seed = unchecked(geography.WorldSeed * 486187739 + 19);
        foreach (var character in geography.SiteId)
            seed = unchecked(seed * 31 + character);
        var random = new Random(seed);
        var kind = SelectKind(node, geography);
        var mountain = kind is "mountain-pass" or "mountain-monastery";
        var obstacles = new List<WorldSiteObstacle>();
        var terrainPatches = new List<WorldSiteTerrainPatch>();
        var localPaths = new List<WorldSiteCorridor>();
        if (mountain)
            AddMountainElevationBands(geography, random, terrainPatches);
        var count = kind switch
        {
            "forest-fork" => 24,
            "forest-trail" => 19,
            "mountain-pass" => 16,
            "mountain-monastery" => 12,
            "monastery-grounds" => 10,
            "wyrm-lair" => 18,
            _ => 12,
        };
        for (var index = 0; index < count; index++)
        {
            // A mountain has two jagged enclosing ridges; the lair has an outer ring of stone ribs.
            // Forests instead have irregular tree/root masses on both sides of the mapped roads.
            var angle = kind == "wyrm-lair"
                ? (index + random.NextDouble() * .45) * Math.PI * 2 / count
                : random.NextDouble() * Math.PI * 2;
            var side = index % 2 == 0 ? 1d : -1d;
            var center = kind switch
            {
                "mountain-pass" or "mountain-monastery" => new HuntPoint(.5 + side * (.285 + random.NextDouble() * .025),
                    .09 + (index / (double)count) * .82 + (random.NextDouble() - .5) * .11),
                "wyrm-lair" => new HuntPoint(.5 + Math.Cos(angle) * (.32 + random.NextDouble() * .08),
                    .5 + Math.Sin(angle) * (.29 + random.NextDouble() * .1)),
                _ => new HuntPoint(.08 + random.NextDouble() * .84, .07 + random.NextDouble() * .86),
            };
            var radiusX = kind switch
            {
                "mountain-pass" or "mountain-monastery" => .15 + random.NextDouble() * .018,
                "wyrm-lair" => .064 + random.NextDouble() * .045,
                "forest-fork" or "forest-trail" => .052 + random.NextDouble() * .042,
                _ => .045 + random.NextDouble() * .042,
            };
            var radiusY = kind switch
            {
                "mountain-pass" or "mountain-monastery" => .13 + random.NextDouble() * .025,
                "wyrm-lair" => .055 + random.NextDouble() * .047,
                _ => .04 + random.NextDouble() * .045,
            };
            if (center.X - radiusX < .012 || center.X + radiusX > .988 ||
                center.Y - radiusY < .012 || center.Y + radiusY > .988)
                continue;
            if (geography.Corridors.Concat(geography.ScenicPaths).Any(corridor => CorridorDistance(center, corridor.Points) < 
                Math.Max(radiusX, radiusY) + corridor.Width * .5 + .065))
                continue;
            // No player spawn, boss telegraph or obligatory encounter crossing is obstructed.
            if (Math.Abs(center.X - .5) < radiusX + .1 && Math.Abs(center.Y - .5) < radiusY + .11)
                continue;
            var material = kind switch
            {
                "mountain-pass" or "mountain-monastery" or "wyrm-lair" => geography.RegionId == "frost"
                    ? WorldSiteSurfaceId.GlacialIce : WorldSiteSurfaceId.Rock,
                "forest-fork" or "forest-trail" => WorldSiteSurfaceId.Grass,
                _ => geography.Substrate.Material,
            };
            var obstacleKind = kind switch
            {
                "mountain-pass" or "mountain-monastery" => geography.RegionId == "frost" ? "glacier-cliff" : "cliff",
                "wyrm-lair" => geography.RegionId == "frost" ? "ice-spire" : "wyrm-rib",
                "forest-fork" or "forest-trail" => "tree-root",
                _ => "rock",
            };
            var outline = Polygon(center, radiusX, radiusY, random);
            obstacles.Add(new WorldSiteObstacle(obstacleKind, material,
                mountain ? 2.2 : kind == "wyrm-lair" ? 1.4 : .5, outline));
        }
        // Small grounded features flank locally generated paths. The number of
        // Chart edges does not determine how many visible roads the arena draws.
        if (kind is "forest-fork" or "forest-trail" or "mountain-pass" or "mountain-monastery")
            AddNearRoadShoulders(geography, mountain, random, obstacles);
        if (mountain)
            AddMountainAnchors(geography, random, obstacles);
        if (geography.GenerationProfile?.Landmark == WorldSiteLandmark.Monastery)
            AddMonasteryBuilding(geography, random, obstacles, terrainPatches, localPaths);
        if (mountain)
            AddMountainCliffFaces(geography, localPaths, random, obstacles);

        // Small seeded side sites share the same C# collision footprints and legal roads.
        // A trace is not a guaranteed reward: some places have already been picked clean.
        var discoveries = AddOptionalDiscoveries(geography, kind, random, obstacles, localPaths);
        return new WorldSiteLandscapeRecipe(kind, obstacles)
        {
            TerrainPatches = terrainPatches,
            LocalPaths = localPaths,
            Discoveries = discoveries,
        };
    }

    private static IReadOnlyList<WorldSiteDiscovery> AddOptionalDiscoveries(
        WorldSiteGeography site, string kind, Random random, IReadOnlyList<WorldSiteObstacle> obstacles,
        List<WorldSiteCorridor> localPaths)
    {
        if (kind != "forest-fork" && random.NextDouble() >= .68) return [];

        const double Width = 950;
        const double Height = 1550;
        var layout = new WorldSiteLandscapeRecipe(kind, obstacles);
        var origin = new HuntPoint(.5, .5);
        var traceKind = kind switch
        {
            "mountain-pass" or "mountain-monastery" => "fallen-pilgrim-cache",
            "wyrm-lair" => "scorched-offering",
            "forest-fork" => "overgrown-ruins",
            "forest-trail" => "forgotten-waystone",
            _ => "abandoned-supplies",
        };

        for (var attempt = 0; attempt < (kind == "forest-fork" ? 64 : 18); attempt++)
        {
            var angle = random.NextDouble() * Math.PI * 2;
            var distance = kind == "forest-fork" ? .13 + random.NextDouble() * .17 : .17 + random.NextDouble() * .13;
            var pocket = new HuntPoint(.5 + Math.Cos(angle) * distance, .5 + Math.Sin(angle) * distance);
            var from = new Vector2D(origin.X * Width, origin.Y * Height);
            var destination = new Vector2D(pocket.X * Width, pocket.Y * Height);
            if (pocket.X is < .1 or > .9 || pocket.Y is < .1 or > .9 ||
                WorldSiteFootprintCollision.BlocksSegment(layout, from, destination, Width, Height, radius: 17))
            {
                continue;
            }

            var id = $"{site.SiteId}:trace";
            localPaths.Add(new WorldSiteCorridor($"{id}:access", WorldSiteSurfaceId.Road, .028, [origin, pocket]));
            // Common salvage only: a site detour cannot bypass Hunt-tier rarity eligibility.
            var material = random.NextDouble() < .43 ? HuntMaterialId.CharredScrap : (HuntMaterialId?)null;
            return [new WorldSiteDiscovery(id, traceKind, pocket, material)];
        }

        return [];
    }

    // Connected foothill/shoulder/crest ribbons follow one seeded mountain
    // spine per side. A ridge is continuous land, not a repeated row of dark
    // rocks. Only explicit cliff footprints block movement: grade is traversable.
    private static void AddMountainElevationBands(
        WorldSiteGeography site, Random random, List<WorldSiteTerrainPatch> terrain)
    {
        var rock = site.RegionId == "frost" ? WorldSiteSurfaceId.GlacialIce : WorldSiteSurfaceId.Rock;
        for (var side = -1; side <= 1; side += 2)
        {
            var phase = random.NextDouble() * Math.PI * 2;
            var bends = Enumerable.Range(0, 13)
                .Select(index => Math.Sin(phase + index * .61) * .018 + (random.NextDouble() - .5) * .026)
                .ToArray();
            foreach (var (kind, height, slope, inner) in new[]
            {
                ("mountain-foothill", .31, .24, .10),
                ("mountain-shoulder", .58, .49, .22),
                ("mountain-crest", .84, .76, .34),
            })
                terrain.Add(new WorldSiteTerrainPatch(kind, rock, height, slope,
                    MountainRidgeStrip(side, inner, bends, random)));
        }
    }

    private static IReadOnlyList<HuntPoint> MountainRidgeStrip(int side, double inner,
        IReadOnlyList<double> bends, Random random)
    {
        var innerEdge = new List<HuntPoint>(bends.Count);
        var outerEdge = new List<HuntPoint>(bends.Count);
        for (var index = 0; index < bends.Count; index++)
        {
            var y = .025 + index / (double)(bends.Count - 1) * .95;
            var drift = bends[index] + (random.NextDouble() - .5) * .012;
            var near = Math.Clamp(inner + drift, .08, .46);
            var far = Math.Clamp(.487 + drift * .35, .465, .489);
            innerEdge.Add(new HuntPoint(.5 + side * near, y));
            outerEdge.Add(new HuntPoint(.5 + side * far, y));
        }
        outerEdge.Reverse();
        innerEdge.AddRange(outerEdge);
        return innerEdge;
    }

    private static void AddNearRoadShoulders(
        WorldSiteGeography site, bool mountain, Random random, List<WorldSiteObstacle> obstacles)
    {
        foreach (var corridor in site.ScenicPaths)
        {
            if (corridor.Points.Count < 2) continue;
            var from = corridor.Points[0];
            var destination = corridor.Points[^1];
            var dx = destination.X - from.X;
            var dy = destination.Y - from.Y;
            var length = Math.Sqrt(dx * dx + dy * dy);
            if (length < .01) continue;

            // Take the same 35%-65% section in which an actual Hunt's first
            // portrait camera starts. Candidate placement stays entirely in C#.
            var progress = .36 + random.NextDouble() * .22;
            var center = new HuntPoint(from.X + progress * dx, from.Y + progress * dy);
            var offset = mountain ? .19 : .18;
            var radiusX = mountain ? .065 : .045;
            var radiusY = mountain ? .075 : .055;
            foreach (var side in new[] { -1d, 1d })
            {
                var point = new HuntPoint(
                    center.X - dy / length * offset * side,
                    center.Y + dx / length * offset * side);
                if (point.X - radiusX < .02 || point.X + radiusX > .98 ||
                    point.Y - radiusY < .02 || point.Y + radiusY > .98)
                    continue;
                if (site.Corridors.Concat(site.ScenicPaths).Any(route =>
                    CorridorDistance(point, route.Points) < Math.Max(radiusX, radiusY) + route.Width * .5 + .055))
                    continue;
                if (Math.Abs(point.X - .5) < radiusX + .10 &&
                    Math.Abs(point.Y - .5) < radiusY + .11)
                    continue;
                var material = mountain
                    ? site.RegionId == "frost" ? WorldSiteSurfaceId.GlacialIce : WorldSiteSurfaceId.Rock
                    : WorldSiteSurfaceId.Grass;
                var obstacleKind = mountain
                    ? site.RegionId == "frost" ? "glacier-cliff" : "cliff"
                    : "tree-root";
                obstacles.Add(new WorldSiteObstacle(obstacleKind, material,
                    mountain ? 1.5 : .7, Polygon(point, radiusX, radiusY, random)));
            }
        }
    }

    // Tall, physically blocking ridge masses must be present even when a seed
    // has multiple exit-clearance lanes. They are placed in free terrain, never
    // by copying the Chart's graph degree into a fork-shaped mountain road.
    private static void AddMountainAnchors(
        WorldSiteGeography site, Random random, List<WorldSiteObstacle> obstacles)
    {
        var lanes = site.Corridors.Concat(site.ScenicPaths).ToArray();
        var candidates = Enumerable.Range(0, 6)
            .SelectMany(row => Enumerable.Range(0, 7)
                .Select(column => new HuntPoint(.12 + column * .125, .14 + row * .142)))
            .ToArray();
        var anchors = candidates.Select(point => new
        {
            Point = point,
            Clearance = lanes.Min(lane => CorridorDistance(point, lane.Points) - lane.Width * .5),
        }).OrderByDescending(candidate => candidate.Clearance).ToArray();
        var selected = new List<HuntPoint>();
        var material = site.RegionId == "frost" ? WorldSiteSurfaceId.GlacialIce : WorldSiteSurfaceId.Rock;
        var kind = site.RegionId == "frost" ? "glacier-cliff" : "cliff";
        foreach (var candidate in anchors)
        {
            if (selected.Count == 9) break;
            if (candidate.Clearance < .055 ||
                selected.Any(point => Math.Sqrt(Math.Pow(point.X - candidate.Point.X, 2) + Math.Pow(point.Y - candidate.Point.Y, 2)) < .145))
                continue;
            var radius = Math.Clamp((candidate.Clearance - .022) * .58, .025, .068);
            obstacles.Add(new WorldSiteObstacle(kind, material, 2.3,
                Polygon(candidate.Point, radius, radius * 1.12, random)));
            selected.Add(candidate.Point);
        }
    }

    // The highland's inner escarpments are solid C# obstacles, unlike the AR1
    // visual height bands. Only actual world exits, local trails and the
    // monastery approach may cut safe passages through these cliff faces.
    private static void AddMountainCliffFaces(WorldSiteGeography site,
        IReadOnlyList<WorldSiteCorridor> localPaths, Random random, List<WorldSiteObstacle> obstacles)
    {
        // Natural rock shelves are broken, tapered and staggered along contour;
        // a repeated 20-section rectangle wall is neither geology nor a useful
        // 2.5D height cue. Each exposed step represents 1–3 metres of relief.
        const int Sections = 18;
        const double Edge = .023;
        var routes = site.Corridors.Concat(site.ScenicPaths).Concat(localPaths).ToArray();
        var material = site.RegionId == "frost" ? WorldSiteSurfaceId.GlacialIce : WorldSiteSurfaceId.Rock;
        var kind = site.RegionId == "frost" ? "glacier-cliff-face" : "cliff-face";
        var monastery = obstacles.Where(obstacle => obstacle.Kind.StartsWith("monastery-", StringComparison.Ordinal))
            .ToArray();

        foreach (var side in new[] { -1d, 1d })
        {
            var phase = random.NextDouble() * Math.PI * 2;
            for (var index = 0; index < Sections; index++)
            {
                // Leave occasional natural breaks and additional safe saddles.
                // Reserved C# chart and monastery approaches always win.
                if (random.NextDouble() < .12) continue;
                var fromY = Edge + index * (1 - 2 * Edge) / Sections + .003;
                var toY = Edge + (index + 1) * (1 - 2 * Edge) / Sections - .003;
                var midY = (fromY + toY) * .5;
                var contour = .179 + Math.Sin(phase + index * .46) * .025;
                var nextContour = .179 + Math.Sin(phase + (index + 1) * .46) * .025;
                var lowRelief = .024 + random.NextDouble() * .016;
                var highRelief = .032 + random.NextDouble() * .016;
                var fromX = .5 + side * contour;
                var toX = .5 + side * nextContour;
                var face = new WorldSiteObstacle(kind, material, 1 + random.NextDouble() * 2,
                [
                    // Ragged inner lip and wider weathered rock beneath it.
                    new HuntPoint(fromX - side * .006, fromY + .004),
                    new HuntPoint(.5 + side * ((contour + nextContour) * .5 - .012), midY),
                    new HuntPoint(toX - side * .003, toY - .002),
                    new HuntPoint(toX + side * highRelief, toY - .006),
                    new HuntPoint(.5 + side * ((contour + nextContour) * .5 + highRelief + .008), midY + .007),
                    new HuntPoint(fromX + side * lowRelief, fromY),
                ]);

                if (TouchesReservedRoute(face, routes) ||
                    monastery.Any(building => BoundsOverlap(face, building, .025)))
                {
                    continue;
                }

                obstacles.Add(face);
            }
        }
    }

    private static bool TouchesReservedRoute(WorldSiteObstacle cliff, IReadOnlyList<WorldSiteCorridor> routes)
    {
        var candidate = new WorldSiteLandscapeRecipe("cliff-clearance", [cliff]);
        foreach (var route in routes)
        {
            for (var index = 1; index < route.Points.Count; index++)
            {
                var from = route.Points[index - 1];
                var to = route.Points[index];
                if (WorldSiteFootprintCollision.BlocksSegment(candidate,
                    new Vector2D(from.X, from.Y), new Vector2D(to.X, to.Y),
                    1, 1, radius: route.Width * .5 + .027))
                {
                    return true;
                }
            }
        }

        return false;
    }

    private static bool BoundsOverlap(WorldSiteObstacle first, WorldSiteObstacle second, double margin) =>
        first.Outline.Min(point => point.X) < second.Outline.Max(point => point.X) + margin &&
        first.Outline.Max(point => point.X) > second.Outline.Min(point => point.X) - margin &&
        first.Outline.Min(point => point.Y) < second.Outline.Max(point => point.Y) + margin &&
        first.Outline.Max(point => point.Y) > second.Outline.Min(point => point.Y) - margin;

    private static string SelectKind(WyrmrealmMapNode node, WorldSiteGeography geography)
    {
        if (node.Type == WyrmrealmNodeType.Dragon)
            return "wyrm-lair";
        var profile = geography.GenerationProfile;
        if (profile?.Landmark == WorldSiteLandmark.Monastery)
            return profile.Landform == WorldSiteLandform.Mountain ? "mountain-monastery" : "monastery-grounds";
        if (profile?.Landform == WorldSiteLandform.Mountain)
            return "mountain-pass";
        if (node.Habitat is WyrmrealmHabitat.Outskirts or WyrmrealmHabitat.WetForest
            or WyrmrealmHabitat.SnowboundPines or WyrmrealmHabitat.FrozenRoad)
            return (unchecked(geography.WorldSeed * 16777619 + node.Stage * 31 + node.Lane * 131) & 3) == 0
                ? "forest-fork" : "forest-trail";
        return node.Habitat is WyrmrealmHabitat.DesertedVillage or WyrmrealmHabitat.BuriedHamlet
            ? "village-site" : "historic-site";
    }

    // The monastery is a real C# collision layout: a hall and surrounding walls
    // with an open south entrance and navigable courtyard. AR4/AR5 own art/depth.
    private static void AddMonasteryBuilding(WorldSiteGeography site, Random random,
        List<WorldSiteObstacle> obstacles, List<WorldSiteTerrainPatch> terrain, List<WorldSiteCorridor> paths)
    {
        var candidates = new[]
        {
            new HuntPoint(.22, .2), new HuntPoint(.78, .2),
            new HuntPoint(.22, .78), new HuntPoint(.78, .78),
            new HuntPoint(.18, .48), new HuntPoint(.82, .48),
        };
        var best = candidates
            .Select(center => new
            {
                Center = center,
                Clearance = site.Corridors.Concat(site.ScenicPaths)
                    .Min(route => CorridorDistance(center, route.Points) - route.Width * .5),
            })
            .OrderByDescending(candidate => candidate.Clearance)
            .First();
        // Fit a recognizable walled complex into the largest free hilltop,
        // without moving any Chart edge or obstructing its clearance lane.
        var available = Math.Max(.065, best.Clearance - .035);
        var halfWidth = Math.Clamp(available * .76, .055, .135);
        var halfHeight = Math.Clamp(available * .58, .048, .105);
        var cx = best.Center.X;
        var cy = best.Center.Y;
        var stone = site.RegionId == "frost" ? WorldSiteSurfaceId.GlacialIce : WorldSiteSurfaceId.Rock;
        var left = cx - halfWidth;
        var right = cx + halfWidth;
        var north = cy - halfHeight;
        var south = cy + halfHeight;
        var thickness = Math.Min(.017, halfWidth * .20);
        terrain.Add(new WorldSiteTerrainPatch("monastery-terrace", stone, .65, .07,
            Polygon(best.Center, halfWidth + .045, halfHeight + .05, random)));
        terrain.Add(new WorldSiteTerrainPatch("monastery-courtyard", stone, .67, .02,
            Rectangle(left + thickness, north + thickness, right - thickness, south - thickness)));
        // Generate a visible, smooth mountain switchback. The path meanders
        // through the central low ground, then curves around the outer wall
        // before approaching the monastery gate from the south.
        var lowPassY = Math.Min(.955, south + .11);
        paths.Add(new WorldSiteCorridor("monastery-approach", WorldSiteSurfaceId.Road, .04,
            CreateWindingMonasteryApproach(cx, south, lowPassY, random)));
        // Eliminate incidental small rocks/roots on the real structure footprint.
        obstacles.RemoveAll(obstacle => obstacle.Outline.Any(point =>
            point.X > left - .03 && point.X < right + .03 &&
            point.Y > north - .03 && point.Y < south + .03) ||
            TouchesReservedRoute(obstacle, paths));
        obstacles.Add(new WorldSiteObstacle("monastery-hall", stone, 1.8,
            Rectangle(cx - halfWidth * .67, north + thickness, cx + halfWidth * .67, cy - halfHeight * .25)));
        obstacles.Add(new WorldSiteObstacle("monastery-wing", stone, 1.25,
            Rectangle(left + thickness, cy - halfHeight * .03, cx - halfWidth * .6, south - thickness * 1.5)));
        obstacles.Add(new WorldSiteObstacle("monastery-wing", stone, 1.25,
            Rectangle(cx + halfWidth * .6, cy - halfHeight * .03, right - thickness, south - thickness * 1.5)));
        obstacles.Add(new WorldSiteObstacle("monastery-tower", stone, 2.4,
            Rectangle(right - halfWidth * .41, north + thickness, right - thickness, cy - halfHeight * .28)));
        obstacles.Add(new WorldSiteObstacle("monastery-wall", stone, 1.4,
            Rectangle(left, north, right, north + thickness)));
        obstacles.Add(new WorldSiteObstacle("monastery-wall", stone, 1.4,
            Rectangle(left, north, left + thickness, south)));
        obstacles.Add(new WorldSiteObstacle("monastery-wall", stone, 1.4,
            Rectangle(right - thickness, north, right, south)));
        // The gate must accommodate the existing player/enemy collision radius,
        // including the approach angle, even in the smallest seeded monastery.
        var gateHalfWidth = Math.Min(halfWidth - thickness * 1.5, Math.Max(.035, thickness * 2.6));
        obstacles.Add(new WorldSiteObstacle("monastery-wall", stone, 1.4,
            Rectangle(left, south - thickness, cx - gateHalfWidth, south)));
        obstacles.Add(new WorldSiteObstacle("monastery-wall", stone, 1.4,
            Rectangle(cx + gateHalfWidth, south - thickness, right, south)));
    }

    // This path is C# world geometry, not a decorative JS road. Every sampled
    // section is reserved through the existing obstacle/corridor clearance logic.
    private static IReadOnlyList<HuntPoint> CreateWindingMonasteryApproach(double cx, double south,
        double lowPassY, Random random)
    {
        var direction = Math.Sign(cx - .5);
        var ascent = lowPassY - .5;
        var swing = Math.Clamp(Math.Abs(ascent) * .16 + (random.NextDouble() - .5) * .014, .018, .060);
        var start = new HuntPoint(.5, .5);
        var firstBend = new HuntPoint(.5 + direction * swing, .5 + ascent * .30);
        var secondBend = new HuntPoint(.5 - direction * swing * .90, .5 + ascent * .70);
        var saddle = new HuntPoint(.5, lowPassY);
        var gate = new HuntPoint(cx, south + .005);
        var path = new List<HuntPoint> { start };

        AppendCubicPath(path, start,
            new HuntPoint(.5 + direction * swing * .85, .5 + ascent * .08),
            new HuntPoint(firstBend.X, .5 + ascent * .20), firstBend);
        AppendCubicPath(path, firstBend,
            new HuntPoint(firstBend.X, .5 + ascent * .47),
            new HuntPoint(secondBend.X, .5 + ascent * .53), secondBend);
        AppendCubicPath(path, secondBend,
            new HuntPoint(secondBend.X, .5 + ascent * .85),
            new HuntPoint(.5 - direction * swing * .35, lowPassY), saddle);
        AppendCubicPath(path, saddle,
            new HuntPoint(.5 + (cx - .5) * .32, lowPassY),
            new HuntPoint(cx, lowPassY - Math.Min(.04, (lowPassY - south) * .45)), gate);
        return path;
    }

    private static void AppendCubicPath(List<HuntPoint> path, HuntPoint start, HuntPoint controlA,
        HuntPoint controlB, HuntPoint end)
    {
        const int Steps = 8;
        for (var index = 1; index <= Steps; index++)
        {
            var t = index / (double)Steps;
            var u = 1 - t;
            path.Add(new HuntPoint(
                u * u * u * start.X + 3 * u * u * t * controlA.X + 3 * u * t * t * controlB.X + t * t * t * end.X,
                u * u * u * start.Y + 3 * u * u * t * controlA.Y + 3 * u * t * t * controlB.Y + t * t * t * end.Y));
        }
    }

    private static IReadOnlyList<HuntPoint> Rectangle(double left, double top, double right, double bottom) =>
    [
        new HuntPoint(left, top), new HuntPoint(right, top),
        new HuntPoint(right, bottom), new HuntPoint(left, bottom),
    ];

    private static IReadOnlyList<HuntPoint> Polygon(HuntPoint center, double radiusX, double radiusY, Random random)
    {
        const int Sides = 9;
        var offset = random.NextDouble() * .3;
        var outline = new HuntPoint[Sides];
        for (var corner = 0; corner < Sides; corner++)
        {
            var angle = corner * Math.PI * 2 / Sides + offset;
            var reach = .85 + random.NextDouble() * .13;
            outline[corner] = new HuntPoint(center.X + Math.Cos(angle) * radiusX * reach,
                center.Y + Math.Sin(angle) * radiusY * reach);
        }
        return outline;
    }

    private static double CorridorDistance(HuntPoint center, IReadOnlyList<HuntPoint> points)
    {
        var shortest = double.PositiveInfinity;
        for (var index = 1; index < points.Count; index++)
        {
            var from = points[index - 1];
            var to = points[index];
            var dx = to.X - from.X;
            var dy = to.Y - from.Y;
            var squared = dx * dx + dy * dy;
            var t = squared < 1e-9 ? 0 : Math.Clamp(
                ((center.X - from.X) * dx + (center.Y - from.Y) * dy) / squared, 0, 1);
            shortest = Math.Min(shortest, Math.Sqrt(Math.Pow(center.X - from.X - dx * t, 2) +
                Math.Pow(center.Y - from.Y - dy * t, 2)));
        }
        return shortest;
    }
}

/// <summary>Shared exact polygon footprints for C# movement, sight, projectiles and visual snapshots.</summary>
public static class WorldSiteFootprintCollision
{
    /// <summary>True when a swept circle hits an authoritative site footprint.</summary>
    public static bool BlocksSegment(WorldSiteLandscapeRecipe? recipe, Vector2D from, Vector2D to,
        double width, double height, double radius = 0)
    {
        if (recipe is null || width <= 0 || height <= 0) return false;
        // Projectile sweeps and visibility raycasts run on the gameplay hot path.
        // Iterate existing C# polygons without Zip/Skip/Append iterator allocations.
        var radiusSquared = radius * radius;
        foreach (var obstacle in recipe.Obstacles)
        {
            if (Contains(obstacle, from, width, height, radius) ||
                Contains(obstacle, to, width, height, radius))
                return true;
            var outline = obstacle.Outline;
            for (var index = 0; index < outline.Count; index++)
            {
                var a = outline[index];
                var b = outline[(index + 1) % outline.Count];
                if (SegmentsDistanceSquared(from, to,
                    new Vector2D(a.X * width, a.Y * height),
                    new Vector2D(b.X * width, b.Y * height)) <= radiusSquared)
                    return true;
            }
        }
        return false;
    }

    /// <summary>True when a physical point or circle lies inside a site polygon.</summary>
    public static bool Contains(WorldSiteObstacle obstacle, Vector2D position, double width, double height, double radius = 0)
    {
        if (width <= 0 || height <= 0 || obstacle.Outline.Count < 3) return false;
        var x = position.X / width;
        var y = position.Y / height;
        var inside = false;
        for (var index = 0; index < obstacle.Outline.Count; index++)
        {
            var a = obstacle.Outline[index];
            var b = obstacle.Outline[(index + 1) % obstacle.Outline.Count];
            if ((a.Y > y) != (b.Y > y) &&
                x < (b.X - a.X) * (y - a.Y) / (b.Y - a.Y) + a.X)
                inside = !inside;
            if (radius > 0 &&
                PointSegmentDistanceSquared(position,
                    new Vector2D(a.X * width, a.Y * height),
                    new Vector2D(b.X * width, b.Y * height)) <= radius * radius)
                return true;
        }
        return inside;
    }

    private static double PointSegmentDistanceSquared(Vector2D point, Vector2D from, Vector2D to)
    {
        var delta = to - from;
        var squared = delta.X * delta.X + delta.Y * delta.Y;
        var t = squared <= 1e-12 ? 0 : Math.Clamp(((point.X - from.X) * delta.X +
            (point.Y - from.Y) * delta.Y) / squared, 0, 1);
        var closest = point - (from + delta * t);
        return closest.X * closest.X + closest.Y * closest.Y;
    }

    private static double SegmentsDistanceSquared(Vector2D a, Vector2D b, Vector2D c, Vector2D d)
    {
        // Crossed segments have distance zero; otherwise use nearest endpoint-to-segment.
        var ab = b - a;
        var cd = d - c;
        var denominator = ab.X * cd.Y - ab.Y * cd.X;
        if (Math.Abs(denominator) > 1e-10)
        {
            var ac = c - a;
            var s = (ac.X * cd.Y - ac.Y * cd.X) / denominator;
            var t = (ac.X * ab.Y - ac.Y * ab.X) / denominator;
            if (s >= 0 && s <= 1 && t >= 0 && t <= 1) return 0;
        }
        return Math.Min(Math.Min(PointSegmentDistanceSquared(a, c, d),
            PointSegmentDistanceSquared(b, c, d)),
            Math.Min(PointSegmentDistanceSquared(c, a, b), PointSegmentDistanceSquared(d, a, b)));
    }
}
