def mesh(name, vertices, faces, collection=forms, mat=clay, smooth=True):
    data = bpy.data.meshes.new(name)
    data.from_pydata(vertices, [], faces)
    data.update()
    ob = bpy.data.objects.new(name, data)
    collection.objects.link(ob)
    ob.data.materials.append(mat)
    for poly in data.polygons:
        poly.use_smooth = smooth
    # Recalculate using BMesh, preserving the authored shape.
    import bmesh
    bm = bmesh.new()
    bm.from_mesh(data)
    bmesh.ops.recalc_face_normals(bm, faces=list(bm.faces))
    bm.to_mesh(data)
    bm.free()
    return ob

def interpolate(stations, steps=5):
    # Catmull-Rom through explicit landmarks, including radius dimensions.
    result = []
    for i in range(len(stations) - 1):
        p0 = stations[max(0, i-1)]
        p1 = stations[i]
        p2 = stations[i+1]
        p3 = stations[min(len(stations)-1, i+2)]
        for j in range(steps):
            t = j / steps
            result.append(tuple(0.5 * ((2*b) + (-aa+c)*t +
                (2*aa-5*b+4*c-d)*t*t + (-aa+3*b-3*c+d)*t*t*t)
                for aa, b, c, d in zip(p0, p1, p2, p3)))
    return result + [stations[-1]]

def tube(name, stations, collection=forms, mat=clay, sides=20, steps=5):
    # Each station: x,y,z,width,depth in the transported transverse frame.
    s = interpolate(stations, steps)
    verts, faces = [], []
    for i, v in enumerate(s):
        center = Vector(v[:3])
        tangent = Vector(s[min(i+1, len(s)-1)][:3]) - Vector(s[max(0, i-1)][:3])
        tangent.normalize()
        side = tangent.cross(Vector((0, 0, 1)))
        if side.length < 0.01:
            side = tangent.cross(Vector((0, 1, 0)))
        side.normalize()
        up = side.cross(tangent).normalized()
        for j in range(sides):
            theta = j * math.tau / sides
            point = center + side * (max(0.003, v[3]) * math.cos(theta)) + up * (max(0.003, v[4]) * math.sin(theta))
            verts.append(tuple(point))
    for i in range(len(s)-1):
        for j in range(sides):
            n = (j+1) % sides
            faces.append((i*sides+j, i*sides+n, (i+1)*sides+n, (i+1)*sides+j))
    faces.extend([tuple(reversed(range(sides))), tuple((len(s)-1)*sides+j for j in range(sides))])
    return mesh(name, verts, faces, collection, mat)

def mirrored(stations, sign):
    return [(sign*x, y, z, w, d) for x, y, z, w, d in stations]

